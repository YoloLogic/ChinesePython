class 字典写表:

    def __init__(self, f, fieldnames, restval='', extrasaction='raise', dialect='excel', *args, **kwds):
        if fieldnames is not None and iter(fieldnames) is fieldnames:
            fieldnames = list(fieldnames)
        self.字段名 = fieldnames
        self.剩余值 = restval
        extrasaction = extrasaction.lower()
        if extrasaction not in ('raise', 'ignore'):
            raise ValueError("extrasaction (%s) must be 'raise' or 'ignore'" % extrasaction)
        self.多余字段怎么处理 = extrasaction
        self.writer = writer(f, dialect, *args, **kwds)

    def 写表头(self):
        header = dict(zip(self.字段名, self.字段名))
        return self.写一行(header)

    def _dict_to_list(self, rowdict):
        if self.多余字段怎么处理 == 'raise':
            wrong_fields = rowdict.keys() - self.字段名
            if wrong_fields:
                raise ValueError('dict contains fields not in fieldnames: ' + ', '.join([repr(x) for x in wrong_fields]))
        return (rowdict.get(key, self.剩余值) for key in self.字段名)

    def 写一行(self, rowdict):
        return self.writer.writerow(self._dict_to_list(rowdict))

    def 写多行(self, rowdicts):
        return self.writer.writerows(map(self._dict_to_list, rowdicts))
